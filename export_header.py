"""
export_header.py - Step 6: hand the winning model to a firmware engineer.

Writes the squashed network as a C header file: integer weight codes, one
scale per layer, and the biases. On the microcontroller,
    real_weight = code * scale

Honest limits (also in the README):
  * codes are written one per byte (int8_t) so the file is easy to read.
    Packing them down to 2-6 bits each - which is what the size numbers in
    this project assume - is the remaining firmware step.
  * this has NOT been compiled or run on a real board.
"""

import numpy as np

from problem import N_LAYERS, prune_weights, quantise_weights


def export_header(problem, recipe, path):
    bits, prune = problem.decode(recipe)
    card = problem.score_card(recipe)
    lines = [
        "// Generated by FlashFit - do not edit by hand.",
        f"// Recipe (bits per layer): {bits}   (prune % per layer): {prune}",
        f"// Packed size: {card['size_bytes']} bytes "
        f"(budget {problem.budget_bytes}), validation error {card['error_pct']:.2f}%",
        "// real_weight = code * scale. Zero codes are pruned weights.",
        "#ifndef FLASHFIT_MODEL_H", "#define FLASHFIT_MODEL_H",
        "#include <stdint.h>", "",
        f"#define FLASHFIT_N_LAYERS {N_LAYERS}", "",
    ]
    for i, (W, b) in enumerate(zip(problem.weights, problem.biases)):
        codes, scale = quantise_weights(prune_weights(W, prune[i]), bits[i])
        rows, cols = W.shape
        lines += [
            f"// Layer {i + 1}: {rows} inputs -> {cols} outputs, "
            f"{bits[i]}-bit codes, {prune[i]}% pruned",
            f"#define FLASHFIT_L{i + 1}_IN {rows}",
            f"#define FLASHFIT_L{i + 1}_OUT {cols}",
            f"static const float flashfit_l{i + 1}_scale = {scale:.8e}f;",
            f"static const int8_t flashfit_l{i + 1}_codes[{rows * cols}] = {{",
        ]
        flat = codes.flatten()
        for start in range(0, len(flat), 24):
            lines.append("  " + ", ".join(str(int(c)) for c in flat[start:start + 24]) + ",")
        lines += ["};",
                  f"static const float flashfit_l{i + 1}_bias[{cols}] = {{ "
                  + ", ".join(f"{v:.6e}f" for v in b) + " };", ""]
    lines.append("#endif  // FLASHFIT_MODEL_H")
    with open(path, "w") as f:
        f.write("\n".join(lines) + "\n")


if __name__ == "__main__":
    import json
    from problem import load_problem
    problem, _ = load_problem()
    recipe = json.load(open("results/best_recipe.json"))["recipe"]
    export_header(problem, recipe, "results/flashfit_model.h")
    print("Wrote results/flashfit_model.h")
